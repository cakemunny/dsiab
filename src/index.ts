/* =============================================================================
   src/index.ts — THE PUBLIC SURFACE
   -----------------------------------------------------------------------------
   Everything a consumer can `import { … } from "dsiab"` is in this file,
   and nothing else is. It has three sections, and they are governed differently:

     1. THEME — `Provider` and the types needed to write a wrapper against it.
        Hand-listed here; short enough to read, and each name is a decision.
     2. COMPONENTS — re-exported from `./components/ui`, which is GENERATED from
        `registry.json` by `scripts/gen-barrel.mjs`. Registering a component is
        what publishes it; nothing reaches a consumer without a registry entry.
        The specifier list below is GENERATED by that same command, between the
        `gen-barrel:begin` / `gen-barrel:end` markers — a hand-kept mirror of the
        barrel would drift the moment someone added a component and refreshed only
        one of the two files. Edit `registry.json`, then run `npm run barrel`.
     3. RADIX GAP-FILLERS — a CURATED subset of the names `@radix-ui/themes`
        exports that this system does not wrap. Radix publishes 103 names; this
        system wraps 57 of them and leaves 46 unwrapped. The 46 were ruled one at
        a time: 30 ship as Radix's OWN binding — 20 named in section 3 below, 10
        through a registered component whose module is a bare re-export — and 16
        do not ship at all. Adding a name to section 3 is a DECISION about what
        this system endorses, not a convenience.

   THE CENSUS, AND THE GUARD THAT KEEPS IT TRUE
   -----------------------------------------------------------------------------
   `src/foundations/radix-surface.node-check.ts` re-derives every number below
   from `@radix-ui/themes`'s own export surface on each test run, and reads them
   back out of this block. They are the record, not a description of one, and a
   stale one fails the suite:

     radix-names            103   every name `@radix-ui/themes` exports
     wrapped                 57   the binding a consumer gets is this system's own
     kept                    30   the binding is Radix's own, re-exported on purpose
       in-section-3          20   named one by one in section 3 below
       through-a-component   10   a registered module whose body is one re-export
     dropped                 16   not exported at all; the reasons close this file

   CORRECTED 2026-08-05 — this block previously read 67 wrapped / 36 unwrapped.
   Ten names (`AspectRatio`, `Grid`, `Section`, `Skeleton`, `VisuallyHidden` and
   their five `*Props`) were counted as wrapped while shipping Radix's own
   binding, and section 3 below positively called two of them "wrapped". The old
   figures added up — 67 + 36 = 103 — which is why nobody checked them against
   Radix; an internally consistent count is not a measured one. The guard is the
   difference, and it fails on a Radix release that adds a name too.

   WHY EVERY RE-EXPORT IS NAMED, AND `export *` APPEARS NOWHERE
   -----------------------------------------------------------------------------
   A name exported by two `export *` statements is silently DROPPED by the ES
   module spec — no error, at build time or at run time. A name exported by one
   `export *` and one explicit statement is silently SHADOWED by the explicit
   one. Both failures land exactly where they cost the most: 57 names carry a
   binding of this system's own AND a Radix binding of the same name, so a star
   re-export would decide those 57 collisions by accident, and a `Box` wrapper
   added tomorrow would lose to Radix's `Box` without a word. (The 30 kept names
   are not collisions — both stars resolve to the same binding, and a name whose
   two stars agree survives; only a genuine disagreement is dropped.) Written out
   name by name, the same collision is a compile error ("Module … has already
   exported a member named 'Box'") the moment it is introduced.
   ============================================================================= */

