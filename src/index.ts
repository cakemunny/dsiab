/* ---- 2. Components --------------------------------------------------------
   Generated from `src/components/ui/index.ts`, which is itself generated from
   `registry.json`.

   ONE NAME IN THE LIST IS NOT A COMPONENT. `useOptionalFieldControl` reads the
   `Field.Root` above it and returns that field's `id` / `aria-describedby` /
   `aria-invalid`, or `null` when there is no Field.Root above it. Read what that
   means from OUT HERE, because it is not what it means inside this repo: the
   `Field` shell is internal by ruling and is NOT exported, so the only Field.Roots
   in a consumer's tree are the ones the inputs render for themselves. The hook
   therefore answers non-null only from inside one of those inputs — content passed
   into a `TextField`'s slot, say — and `null` everywhere else. It cannot be used to
   give a hand-built control the shell's label / description / validation chrome,
   because reaching that needs `Field.Root`, and `Field.Root` does not ship.

   THE SUPPORTED WAY TO GET AN INPUT WITH LABEL, HELPER TEXT AND VALIDATION is the
   wrapped inputs, which ride the shell already and hand it to you as props —
   `label`, `description`, `validation`, and `info` / `endSlot` where the label row
   takes them. Which components those are is deliberately not a roster here (a
   roster in prose is a copy that rots): every input's `Props` story carries its own
   prop table, and `validation?:` under src/components/ui finds them all at once.
   Composing the shell by hand is not a supported extension point — it is a second
   way to build an input that bypasses the rules the wrappers exist to enforce.

   `Field`'s registry entry publishes that one hook and lists the other fifteen
   names it withholds, this one included. GROUP-LEVEL VALIDATION IS A KNOWN GAP:
   `FieldGroup` is withheld too, and `CheckboxGroup` / `RadioGroup` take no `label`
   or `validation` of their own, so a group-level error message has no published
   route today. */
